/**
 * Bulk import from a CSV, for every kind of record the office types in:
 *
 *   clients              new clients
 *   nxp                  new NXP records (linked to a client by name)
 *   inspection_requests  new inspection requests for existing NXP records
 *   assignments          inspectors assigned to open requests (creates the inspections)
 *   trade_details        trade / banking details on existing NXP records (CCI boxes)
 *   shipment_details     shipment / NESS details, incl. the exchange rate, on inspections
 *   users                new staff accounts
 *
 * Inspection findings are captured by the inspector's device and certificates
 * are generated by the system, so neither is imported.
 *
 * The preview and the real run are the SAME code path: every row is actually
 * written, inside a transaction, and the preview simply rolls that transaction
 * back at the end. So a preview can't disagree with what a commit will do —
 * every rule the normal single-record forms enforce (they go through the same
 * services) applies here too, including the ones the database enforces, like a
 * duplicate key.
 *
 * A commit is all-or-nothing: if any row fails, nothing is written. That is the
 * behaviour people expect of "import this spreadsheet" — a half-loaded file is
 * worse than a rejected one, because you can't tell by looking which half.
 *
 * The two "details" types UPDATE existing records, and only the cells that are
 * filled in: a blank cell leaves the current value as it is, so a sheet with
 * just `nxp_number,exchange_rate` sets exchange rates and touches nothing else.
 */
